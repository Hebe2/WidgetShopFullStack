package dao;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;

import domain.Customer;
import org.jdbi.v3.core.Jdbi;
import org.jdbi.v3.sqlobject.SqlObjectPlugin;
import org.junit.jupiter.api.Test;

class CustomerJdbiDAOTest {

    @Test
    void saveGeneratesCustomerId() {
        Jdbi jdbi = Jdbi.create("jdbc:h2:mem:customer-registration;DB_CLOSE_DELAY=-1");
        jdbi.installPlugin(new SqlObjectPlugin());
        jdbi.useHandle(handle -> handle.execute("""
                CREATE TABLE Customer (
                    customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR(100) NOT NULL,
                    first_name VARCHAR(100) NOT NULL,
                    last_name VARCHAR(100) NOT NULL,
                    shipping_address VARCHAR(200) NOT NULL,
                    email_address VARCHAR(200) NOT NULL,
                    password VARCHAR(100) NOT NULL
                )
                """));

        Customer customer = new Customer();
        customer.setUsername("testuser");
        customer.setFirstName("Test");
        customer.setSurname("User");
        customer.setShippingAddress("1 Test Street");
        customer.setEmailAddress("test@example.com");
        customer.setPassword("test123");

        CustomerJdbiDAO dao = jdbi.onDemand(CustomerJdbiDAO.class);
        dao.save(customer);

        assertNotNull(customer.getCustomerId());
        assertEquals("testuser", dao.getByUsername("testuser").getUsername());
    }
}
